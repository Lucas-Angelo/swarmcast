import fs from 'node:fs';
import path from 'node:path';
import { playlistEntries, SEGMENT_DURATION_S } from '@swarmcast/shared';
import type { Logger } from '../core/logger.js';
import { ManagedChild, type Reaper } from '../process/children.js';

export interface MediaMtxOptions {
  binary: string;
  runDir: string;
  rtmpPort: number;
  hlsPort: number;
  streamKey: string;
}

/** Path MediaMTX publishes on. OBS: server rtmp://127.0.0.1:1935/live, key <streamKey>. */
export function streamPath(streamKey: string): string {
  return `live/${streamKey}`;
}

/**
 * Generate the MediaMTX config. Everything listens on 127.0.0.1 only; every protocol
 * except RTMP ingest and local HLS is disabled. The stream key is part of the only
 * configured path, so publishing to any other path is rejected.
 */
export function renderMediaMtxConfig(o: Omit<MediaMtxOptions, 'binary' | 'runDir'>): string {
  if (!/^[A-Za-z0-9_-]{8,}$/.test(o.streamKey)) throw new Error('stream key has invalid characters');
  const p = streamPath(o.streamKey);
  return [
    '# Generated by SwarmCast. Do not edit: it is rewritten on every start.',
    'logLevel: info',
    'logDestinations: [stdout]',
    'authMethod: internal',
    'authInternalUsers:',
    '  - user: any',
    "    ips: ['127.0.0.1/32', '::1/128']",
    '    permissions:',
    '      - action: publish',
    `        path: ${p}`,
    '      - action: read',
    `        path: ${p}`,
    'api: false',
    'metrics: false',
    'pprof: false',
    'playback: false',
    'rtsp: false',
    'webrtc: false',
    'srt: false',
    'moq: false',
    'rtmp: true',
    `rtmpAddress: 127.0.0.1:${o.rtmpPort}`,
    'hls: true',
    `hlsAddress: 127.0.0.1:${o.hlsPort}`,
    'hlsAllowOrigins: []',
    'hlsAlwaysRemux: true',
    // Standard fMP4 HLS (not LL-HLS): plain segments are what P2P can share.
    'hlsVariant: fmp4',
    // Enough segments to cover PLAYLIST_WINDOW_S (the furthest behind live a player sits).
    `hlsSegmentCount: ${playlistEntries(SEGMENT_DURATION_S)}`,
    // Minimum duration: MediaMTX cuts at the first keyframe after it, so with OBS keyframes
    // every SEGMENT_DURATION_S seconds the segments are exactly that long. Using the full
    // value here would round 1.999 s up to the next keyframe (4 s segments).
    `hlsSegmentDuration: ${Math.max(1, SEGMENT_DURATION_S / 2)}s`,
    'paths:',
    `  ${p}:`,
    '    source: publisher',
    '',
  ].join('\n');
}

export type PublishEvent = 'publishing' | 'unpublished';

export class MediaMtx {
  private child: ManagedChild | null = null;
  onPublish: (e: PublishEvent) => void = () => {};

  constructor(
    private readonly opts: MediaMtxOptions,
    private readonly reaper: Reaper | null,
    private readonly log: Logger,
  ) {}

  get pid(): number | undefined {
    return this.child?.pid;
  }

  get running(): boolean {
    return this.child?.running ?? false;
  }

  async start(): Promise<void> {
    if (!fs.existsSync(this.opts.binary)) {
      throw new Error(`MediaMTX was not found at ${this.opts.binary}. Run the start script again to repair the installation.`);
    }
    fs.mkdirSync(this.opts.runDir, { recursive: true, mode: 0o700 });
    const cfgPath = path.join(this.opts.runDir, 'mediamtx.yml');
    fs.writeFileSync(cfgPath, renderMediaMtxConfig(this.opts), { mode: 0o600 });

    const child = new ManagedChild('mediamtx', this.opts.binary, [cfgPath], { cwd: this.opts.runDir }, this.reaper, this.log);
    this.child = child;
    let ready = false;
    let publisherConn: string | null = null;
    const readyPromise = new Promise<void>((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('MediaMTX did not start within 15 seconds.')), 15_000);
      child.on('line', (line) => {
        const clean = line.replaceAll(this.opts.streamKey, '[key]');
        if (/\b(ERR|WAR)\b/.test(clean)) this.log.warn({ mediamtx: clean }, 'mediamtx');
        else this.log.debug({ mediamtx: clean }, 'mediamtx');
        if (!ready && /\[HLS\] (listener opened|started with listener)/.test(line)) {
          ready = true;
          clearTimeout(timer);
          resolve();
        }
        // Track the publisher's connection: readers (the quality-ladder ffmpeg) also open and
        // close RTMP connections, and their "closed" must not look like OBS leaving.
        const conn = /\[RTMP\] \[conn ([^\]]+)\]/.exec(line)?.[1];
        if (/is publishing to path/.test(line)) {
          publisherConn = conn ?? null;
          this.onPublish('publishing');
        }
        if (conn && /\[RTMP\] \[conn [^\]]+\] closed/.test(line) && !/is not configured/.test(line) && (publisherConn === null || conn === publisherConn)) {
          publisherConn = null;
          this.onPublish('unpublished');
        }
        if (/address already in use|bind: /i.test(line)) {
          clearTimeout(timer);
          reject(new Error(`A port needed by MediaMTX is already in use (${this.opts.rtmpPort} or ${this.opts.hlsPort}). Close the other program (maybe another SwarmCast or OBS plugin) and try again.`));
        }
      });
      child.once('exit', (code) => {
        clearTimeout(timer);
        if (!ready) reject(new Error(`MediaMTX exited during startup (code ${code}). See the log for details.`));
      });
    });
    await readyPromise;
  }

  async stop(): Promise<void> {
    await this.child?.stop();
    this.child = null;
  }
}
