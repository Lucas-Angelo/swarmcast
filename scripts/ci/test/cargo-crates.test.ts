// .github/scripts/cargo-crates.mjs: the Rust crates the cargo jobs take from a saved artifact
// instead of crates.io. Which crates a Cargo.lock needs and the artifact's name for it, the check
// of a registry against Cargo.lock's checksums, which failed `cargo fetch` the cold path tries
// again (the network, such as crates.io's CDN answering 206 in release rehearsal 42799834042)
// and which it does not.
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { FETCH_PAUSES_MS, artifactName, checkCrates, fetchWithTries, lockedCrates, networkError } from '../../../.github/scripts/cargo-crates.mjs';

const CRATES_IO = 'registry+https://github.com/rust-lang/crates.io-index';
const REGISTRY_DIR = 'index.crates.io-1949cf8c6b5b557f';
const sha256 = (data: string) => crypto.createHash('sha256').update(data).digest('hex');

/** A Cargo.lock with the workspace crate and `packages` ([name, version, contents of its .crate]). */
function lockfile(packages: [string, string, string][], extra = '') {
  const blocks = packages.map(([name, version, data]) => `[[package]]\nname = "${name}"\nversion = "${version}"\nsource = "${CRATES_IO}"\nchecksum = "${sha256(data)}"\n`);
  return ['# This file is automatically @generated by Cargo.', 'version = 4', '', '[[package]]\nname = "swarmcast-desktop"\nversion = "0.5.2"\ndependencies = [\n "adler2",\n]\n', ...blocks, extra].join('\n');
}

const PACKAGES: [string, string, string][] = [
  ['adler2', '2.0.1', 'adler2 crate bytes'],
  ['pxfm', '0.1.30', 'pxfm crate bytes'],
];

let dir: string;
beforeEach(() => {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cargo-crates-test-'));
});
afterEach(() => {
  fs.rmSync(dir, { recursive: true, force: true });
});

/** A registry with the .crate files `files` ([name, version, contents]) in its crates.io folder. */
function registry(files: [string, string, string][]) {
  const cache = path.join(dir, 'registry', 'cache', REGISTRY_DIR);
  fs.mkdirSync(cache, { recursive: true });
  for (const [name, version, data] of files) fs.writeFileSync(path.join(cache, `${name}-${version}.crate`), data);
  return path.join(dir, 'registry');
}

describe('lockedCrates', () => {
  it("lists the crates.io packages with their checksums, not the workspace's own crate", () => {
    // Act
    const crates = lockedCrates(lockfile(PACKAGES));

    // Assert
    expect(crates).toEqual([
      { name: 'adler2', version: '2.0.1', checksum: sha256('adler2 crate bytes') },
      { name: 'pxfm', version: '0.1.30', checksum: sha256('pxfm crate bytes') },
    ]);
  });

  it('reads a lockfile with Windows line ends the same way', () => {
    // Act
    const crates = lockedCrates(lockfile(PACKAGES).replace(/\n/g, '\r\n'));

    // Assert
    expect(crates.map((c) => c.name)).toEqual(['adler2', 'pxfm']);
  });

  it('refuses a package from outside crates.io, which the saved crates would not hold', () => {
    // Arrange
    const git = '[[package]]\nname = "forked"\nversion = "1.0.0"\nsource = "git+https://github.com/example/forked?rev=abc#abc"\n';

    // Act
    const read = () => lockedCrates(lockfile(PACKAGES, git));

    // Assert
    expect(read).toThrow(/outside crates\.io.*forked 1\.0\.0/);
  });

  it('refuses a crates.io package without a checksum', () => {
    // Arrange
    const lock = lockfile(PACKAGES).replace(/checksum = "[0-9a-f]+"\n/, '');

    // Act
    const read = () => lockedCrates(lock);

    // Assert
    expect(read).toThrow(/adler2 2\.0\.1 has no checksum/);
  });
});

describe('artifactName', () => {
  it('names the toolchain and the lockfile, whatever its line ends', () => {
    // Arrange
    const lock = lockfile(PACKAGES);

    // Act
    const names = [artifactName(lock, '1.99.1'), artifactName(lock.replace(/\n/g, '\r\n'), '1.99.1')];

    // Assert
    expect(names[0]).toMatch(/^cargo-crates-1\.99\.1-[0-9a-f]{16}$/);
    expect(names[1]).toBe(names[0]);
  });

  it('changes with the lockfile and with the toolchain', () => {
    // Arrange
    const lock = lockfile(PACKAGES);

    // Act
    const names = new Set([artifactName(lock, '1.99.1'), artifactName(lockfile(PACKAGES.slice(1)), '1.99.1'), artifactName(lock, '1.100.0')]);

    // Assert
    expect(names.size).toBe(3);
  });
});

describe('checkCrates', () => {
  it('passes a registry that holds every crate with its checksum', () => {
    // Arrange
    const reg = registry(PACKAGES);

    // Act
    const result = checkCrates(lockedCrates(lockfile(PACKAGES)), reg);

    // Assert
    expect(result).toEqual({ dir: REGISTRY_DIR, ok: 2, missing: [], wrong: [] });
  });

  it('names a missing crate and one whose bytes are not the ones Cargo.lock records', () => {
    // Arrange
    const reg = registry([['adler2', '2.0.1', 'something else']]);

    // Act
    const result = checkCrates(lockedCrates(lockfile(PACKAGES)), reg);

    // Assert
    expect(result).toEqual({ dir: REGISTRY_DIR, ok: 0, missing: ['pxfm 0.1.30'], wrong: ['adler2 2.0.1'] });
  });

  it('finds every crate missing in a registry with no crates.io folder', () => {
    // Act
    const result = checkCrates(lockedCrates(lockfile(PACKAGES)), path.join(dir, 'registry'));

    // Assert
    expect(result).toEqual({ dir: null, ok: 0, missing: ['adler2 2.0.1', 'pxfm 0.1.30'], wrong: [] });
  });
});

