const RUN_42799834042 = [
  '  Downloaded proc-macro2 v1.0.107',
  'error: failed to download from `https://static.crates.io/crates/pxfm/0.1.30/download`',
  '',
  'Caused by:',
  '  failed to get successful HTTP response from `https://static.crates.io/crates/pxfm/0.1.30/download` (3.168.51.17), got 206',
  '  debug headers:',
  '  x-cache: Hit from cloudfront',
  '  body:',
  '  [879463 non-utf8 bytes]',
].join('\n');

/** cargo fetch with the registry unreachable (a local run through a proxy that refuses). */
const UNREACHABLE = [
  'error: failed to get `adler2` as a dependency of package `swarmcast-desktop v0.5.2`',
  '',
  'Caused by:',
  '  download of config.json failed',
  '',
  'Caused by:',
  "  [7] Couldn't connect to server (Failed to connect to 127.0.0.1 port 9 after 0 ms: Couldn't connect to server)",
].join('\n');

const LOCK_OUTDATED = 'error: the lock file /w/apps/desktop/src-tauri/Cargo.lock needs to be updated but --locked was passed to prevent this';

describe('networkError', () => {
  it("finds crates.io's 206 answer of run 42799834042, which cargo does not try again", () => {
    // Act
    const line = networkError(RUN_42799834042);

    // Assert
    expect(line).toBe('error: failed to download from `https://static.crates.io/crates/pxfm/0.1.30/download`');
  });

  it('finds an unreachable registry, colour codes and Windows line ends aside', () => {
    // Act
    const line = networkError(`\x1b[1m\x1b[31m${UNREACHABLE.replace(/\n/g, '\r\n')}\x1b[0m`);

    // Assert
    expect(line).toBe('download of config.json failed');
  });

  it('counts a cut-off download that fails its checksum as the network', () => {
    // Act
    const line = networkError('error: failed to verify the checksum of `pxfm v0.1.30`');

    // Assert
    expect(line).toBe('error: failed to verify the checksum of `pxfm v0.1.30`');
  });

  it('finds nothing in a lockfile that needs an update', () => {
    // Act
    const line = networkError(LOCK_OUTDATED);

    // Assert
    expect(line).toBeNull();
  });
});

type Try = { code: number; output: string; timedOut: boolean };
/** A fake `cargo fetch`: one answer per try, in turn; and what the cold path logged and waited. */
function fakeFetch(tries: Try[]) {
  const runs: number[] = [];
  const waited: number[] = [];
  const lines: string[] = [];
  const run = async (tryMs: number) => {
    runs.push(tryMs);
    return tries.shift() ?? { code: 0, output: '', timedOut: false };
  };
  return { run, runs, waited, lines, sleep: async (ms: number) => void waited.push(ms), log: (l: string) => void lines.push(l) };
}
const ok: Try = { code: 0, output: '  Downloaded pxfm v0.1.30', timedOut: false };
const partial: Try = { code: 101, output: RUN_42799834042, timedOut: false };

describe('fetchWithTries', () => {
  it('fetches once when the first try works, with no warning', async () => {
    // Arrange
    const f = fakeFetch([ok]);

    // Act
    const result = await fetchWithTries(f);

    // Assert
    expect(result).toEqual({ tries: 1 });
    expect(f.lines).toEqual([]);
  });

  it('tries again after a network failure and logs the recovery', async () => {
    // Arrange
    const f = fakeFetch([partial, ok]);

    // Act
    const result = await fetchWithTries(f);

    // Assert
    expect(result).toEqual({ tries: 2 });
    expect(f.waited).toEqual([FETCH_PAUSES_MS[0]]);
    expect(f.lines.at(-1)).toMatch(/^::warning title=cargo-crates::infra recovery: cargo fetch from crates\.io worked on try 2 of 3 \(try 1: error: failed to download from/);
  });

  it('tries again after a try it cut off', async () => {
    // Arrange
    const f = fakeFetch([{ code: 1, output: '  Downloaded adler2 v2.0.1', timedOut: true }, ok]);

    // Act
    const result = await fetchWithTries({ ...f, tryMs: 60_000 });

    // Assert
    expect(result).toEqual({ tries: 2 });
    expect(f.lines[0]).toMatch(/try 1 of 3 failed \(cut off after 60 s\)/);
  });

  it('fails at once on an error that is not the network', async () => {
    // Arrange
    const f = fakeFetch([{ code: 101, output: LOCK_OUTDATED, timedOut: false }, ok]);

    // Act
    const fetching = fetchWithTries(f);

    // Assert
    await expect(fetching).rejects.toThrow(/not on the network: not tried again/);
    expect(f.runs).toHaveLength(1);
  });

  it('gives up after its tries, all on the network', async () => {
    // Arrange
    const f = fakeFetch([partial, partial, partial, ok]);

    // Act
    const fetching = fetchWithTries(f);

    // Assert
    await expect(fetching).rejects.toThrow(/failed 3 times on the network/);
    expect(f.runs).toHaveLength(3);
    expect(f.waited).toEqual(FETCH_PAUSES_MS);
  });
});
